import sharp from "sharp";
import { writeFile } from "node:fs/promises";
const fixtures = {};
for (const type of ["jpeg", "png", "webp"]) {
  const bytes = await sharp({
    create: {
      width: 2,
      height: 2,
      channels: 4,
      background: { r: 160, g: 100, b: 40, alpha: 0.5 },
    },
  })
    .toFormat(type)
    .toBuffer();
  fixtures[`image/${type}`] = [...bytes];
}
await writeFile(
  "src/lib/capability-fixtures.ts",
  `// Tiny, locally bundled codec probes. Generated by scripts/capability-fixtures.mjs.\nexport const CODEC_FIXTURES = ${JSON.stringify(fixtures)};\n`,
);
